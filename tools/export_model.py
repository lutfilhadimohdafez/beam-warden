#!/usr/bin/env python3
"""Train a COMPACT RandomForest on self-calibrated telemetry features and export it
to a portable awk tree-walk (model.awk) the OpenWrt router can run with NO python /
sklearn. This is what puts the actual learned model ON the router (OBJ3).

Features (per window), each relative to this network's calibrated baseline so one
model transfers to any network:
  f[0]=retry_ratio  f[1]=retry_z   f[2]=per_ratio  f[3]=per_z
  f[4]=tput_ratio   f[5]=tput_z
Reports leave-one-RUN-out accuracy of the EXACT exported model (honest on-router
number, not the big-forest number).

Run: .venv/bin/python tools/export_model.py data/obj1_*.csv data/real_aba_*.csv
"""
import argparse
import csv
import statistics as st
import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
EPS = 1e-6
METRICS = ["retry_rate", "tx_per_pct", "throughput_tx_mbps", "rssi"]
FEATS = ["retry_ratio", "retry_z", "per_ratio", "per_z",
         "tput_ratio", "tput_z", "rssi_ratio", "rssi_z"]
N_TREES, MAX_DEPTH = 60, 8


def _f(row, k):
    try:
        return float(row.get(k, ""))
    except (TypeError, ValueError):
        return None


def _rssi(row):
    vs = [_f(row, f"rssi{i}") for i in range(4)]
    vs = [v for v in vs if v is not None]
    return st.mean(vs) if vs else None


def load_run(path):
    rows = [{m: (_rssi(r) if m == "rssi" else _f(r, m)) for m in METRICS}
            | {"label": 1 if r.get("label") == "attack" else 0}
            for r in csv.DictReader(open(path))]
    base = {}
    for m in METRICS:
        norm = [r[m] for r in rows if r["label"] == 0 and r[m] is not None]
        base[m] = (st.mean(norm), (st.pstdev(norm) if len(norm) > 1 else 0.0)) if norm else (0.0, 0.0)
    return rows, base


def feats(rec, base):
    out = []
    for m in METRICS:
        mean, std = base[m]
        v = rec[m] if rec[m] is not None else mean
        out += [v / (mean + EPS), (v - mean) / (std + EPS)]
    return out


def tree_to_awk(clf_tree, fname):
    from sklearn.tree import _tree
    t = clf_tree.tree_

    def rec(node):
        if t.feature[node] != _tree.TREE_UNDEFINED:
            return f"(f[{t.feature[node]}]<={t.threshold[node]:.6g}?{rec(t.children_left[node])}:{rec(t.children_right[node])})"
        return str(int(t.value[node][0].argmax()))
    return f"function {fname}(f){{return {rec(0)}}}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("csvs", nargs="+")
    ap.add_argument("--out", default="openwrt/beamwarden/files/model.awk")
    a = ap.parse_args()
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.model_selection import LeaveOneGroupOut, cross_val_score

    X, y, g = [], [], []
    for gi, p in enumerate(a.csvs):
        rows, base = load_run(p)
        for r in rows:
            X.append(feats(r, base)); y.append(r["label"]); g.append(gi)
    print(f"runs: {len(a.csvs)}  samples: {len(y)}  attack {sum(y)} / normal {len(y)-sum(y)}")

    mk = lambda: RandomForestClassifier(n_estimators=N_TREES, max_depth=MAX_DEPTH,
                                        random_state=0, class_weight="balanced")
    if len(a.csvs) >= 2:
        acc = cross_val_score(mk(), X, y, groups=g, cv=LeaveOneGroupOut(), scoring="accuracy")
        print(f"EXPORTED model ({N_TREES} trees, depth {MAX_DEPTH}) leave-one-run-out: "
              f"{acc.mean()*100:.1f}%  per-fold {[f'{x*100:.0f}' for x in acc]}  (target >=55%)")

    clf = mk(); clf.fit(X, y)
    funcs = [tree_to_awk(e, f"t{i}") for i, e in enumerate(clf.estimators_)]
    votes = "".join(f"v+=t{i}(f);" for i in range(N_TREES))
    awk = ("# Beam-Warden model — generated by export_model.py. DO NOT EDIT.\n"
           f"# features: {' '.join(FEATS)}  |  {N_TREES} trees depth {MAX_DEPTH}\n"
           + "\n".join(funcs) + "\n"
           "{n=split($0,a,\" \");for(i=0;i<n;i++)f[i]=a[i+1];v=0;" + votes
           + f"print(v>{N_TREES//2}?1:0)}}\n")
    outp = Path(a.out); outp.parent.mkdir(parents=True, exist_ok=True)
    outp.write_text(awk)
    print(f"wrote {outp}  ({len(awk)} bytes, {N_TREES} trees)")

    # self-check: the awk must reproduce sklearn's predictions
    import subprocess
    agree = 0
    for xi, yi in zip(X, y):
        line = " ".join(f"{v:.6g}" for v in xi)
        r = subprocess.run(["awk", "-f", str(outp)], input=line + "\n",
                           capture_output=True, text=True)
        if int(r.stdout.strip()) == int(clf.predict([xi])[0]):
            agree += 1
    print(f"awk vs sklearn agreement: {agree}/{len(X)} "
          f"({'OK' if agree == len(X) else 'MISMATCH!'})")


if __name__ == "__main__":
    main()
